// Wrap every TS3W.exe address literal in our native sources as TS3A(0x...), so a port to another exe build is a
// generated table instead of hundreds of hand edits (docs/68 §7.1).
//
//   node tools/addr-codemod.ts [scan]          dry run: counts per file + unsure rows; every row -> out/addr-codemod/scan.csv
//   node tools/addr-codemod.ts --apply         rewrite the `wrap` rows in place (idempotent) + include ts3addr.h in ts3native.cpp
//   node tools/addr-codemod.ts gen --map out/exe-addr-map/<exe>.csv [--allow-inferred] [--out file]
//                                              table for `/DTS3A_TABLE` (default native/ts3native/out/ts3addr-table.h, gitignored)
//   node tools/addr-codemod.ts --self-check
//
// Scope: native/ts3native/*.cpp|*.h, no tests (*test*), no generated headers ("Generated by/from" in the first 3 lines:
// fix their generator instead). Literal = 0x + 6-8 hex digits inside the Steam 1.67 image: code (hook-sites scan range) or
// .rdata/.data/.tls (incl. the IAT) from game-copy/bin/TS3W.exe's section table, built-in values when the exe is absent.
// Kinds: wrap; unsure (page-aligned = section bounds/sizes/base, all-F masks, known constants, size/mask/count names next
// to it: decide by hand); manual (where a macro is not wanted: inline asm, #if/#elif, case labels, [] and template args).
// Comments and string literals are skipped. Static initializers are wrapped: TS3A_TABLE's lookup is constexpr and forced
// to compile time, so they stay constant (a missing address is a compile error, never a silent wrong pointer).
// shortcut: raw strings R"(...)" and line continuations are not tokenized; none in ts3native today.
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { scan as hookScan, csvRow } from "./hook-sites.ts";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(repo, "native", "ts3native");
const HUB = "ts3native.cpp";  // unity build: every module is included from here
const INCLUDE = '#include "ts3addr.h"  // TS3A(x): TS3W.exe addresses by Steam 1.67 value (tools/addr-codemod.ts)';

type Range = [number, number, string];
// Steam 1.67 non-code sections (VA, end exclusive); read from the exe when present
const DATA_DEFAULT: Range[] = [[0x00f95000, 0x01145389, ".rdata"], [0x01146000, 0x01234384, ".data"], [0x01235000, 0x01235009, ".tls"]];
export function dataRanges(exe = join(repo, "game-copy", "bin", "TS3W.exe")): Range[] {
    if (!existsSync(exe)) return DATA_DEFAULT;
    const b = readFileSync(exe), pe = b.readUInt32LE(0x3c), n = b.readUInt16LE(pe + 6), opt = pe + 24, base = b.readUInt32LE(opt + 28);
    const out: Range[] = [];
    for (let i = 0, s = opt + b.readUInt16LE(pe + 20); i < n; i++, s += 40) {
        const name = b.toString("latin1", s, s + 8).replace(/\0/g, ""), rva = b.readUInt32LE(s + 12), vsz = b.readUInt32LE(s + 8);
        if ([".rdata", ".data", ".tls"].includes(name)) out.push([base + rva, base + rva + vsz, name]);
    }
    return out;
}

export type Row = { file: string; line: number; col: number; lit: string; addr: number; sect: string; kind: "wrap" | "wrapped" | "unsure" | "manual"; why: string };
const KNOWN = new Set([0x01000193]);  // FNV-1 prime
const NAMEY = /(size|len|mask|count|cnt|flag|max|min|cap|limit|bytes|align)\w*\s*[=(,]?\s*$/i;

export function scanText(text: string, file: string, data: Range[] = DATA_DEFAULT): Row[] {
    const rows: Row[] = [];
    const sectOf = (a: number) => hookScan(`0x${a.toString(16)}`, "").length ? ".text" : data.find(([lo, hi]) => a >= lo && a < hi)?.[2];
    let i = 0, line = 1, lineStart = 0, asmDepth = -1, asmLine = -1, depth = 0;
    let ppKind = "";  // directive of the current preprocessor line ("" = not one)
    const n = text.length;
    while (i < n) {
        const c = text[i];
        if (c === "\n") { line++; lineStart = i + 1; ppKind = ""; i++; continue; }
        if (c === "/" && text[i + 1] === "/") { while (i < n && text[i] !== "\n") i++; continue; }
        if (c === "/" && text[i + 1] === "*") { const e = text.indexOf("*/", i + 2); const end = e < 0 ? n : e + 2; for (let k = i; k < end; k++) if (text[k] === "\n") { line++; lineStart = k + 1; } i = end; continue; }
        if (c === '"' || c === "'") { i++; while (i < n && text[i] !== c && text[i] !== "\n") i += text[i] === "\\" ? 2 : 1; i++; continue; }
        if (c === "#" && /^\s*$/.test(text.slice(lineStart, i))) { ppKind = /^#\s*(\w+)/.exec(text.slice(i, i + 20))?.[1] ?? ""; i++; continue; }
        if (c === "{") { depth++; i++; continue; }
        if (c === "}") { if (depth === asmDepth) asmDepth = -1; depth--; i++; continue; }
        const id = /^[A-Za-z_]\w*/.exec(text.slice(i, i + 64));
        if (id && (i === 0 || !/\w/.test(text[i - 1]))) {
            if (id[0] === "__asm" || id[0] === "_asm") {
                let k = i + id[0].length; while (text[k] === " " || text[k] === "\t" || text[k] === "\r" || text[k] === "\n") k++;
                if (text[k] === "{") asmDepth = depth + 1; else asmLine = line;
            }
            i += id[0].length; continue;
        }
        const m = /^0[xX]([0-9A-Fa-f]{6,8})([uUlL]*)(?![\w.])/.exec(text.slice(i, i + 16));
        if (!m || (i > 0 && /[\w.]/.test(text[i - 1]))) { i++; continue; }
        const addr = parseInt(m[1], 16), sect = sectOf(addr);
        if (sect) {
            const lineText = text.slice(lineStart, text.indexOf("\n", i) < 0 ? n : text.indexOf("\n", i));
            const before = text.slice(lineStart, i), after = lineText.slice(i - lineStart + m[0].length);
            const row: Row = { file, line, col: i - lineStart + 1, lit: m[0], addr, sect, kind: "wrap", why: "" };
            const stmt = before.split(/[;{}]/).pop()!;
            if (/TS3A\(\s*$/.test(before)) row.kind = "wrapped";
            else if (asmDepth >= 0 || asmLine === line) [row.kind, row.why] = ["manual", "inline asm"];
            else if (ppKind && ppKind !== "define") [row.kind, row.why] = ["manual", `#${ppKind}`];
            else if (/\bcase\b[^:]*$/.test(stmt)) [row.kind, row.why] = ["manual", "case label"];
            else if (/\[[^\]]*$/.test(before)) [row.kind, row.why] = ["manual", "inside []"];
            else if (/\b[A-Za-z_]\w*\s*<[^<>;=()&|]*$/.test(before) && /^[^<>;=|&]*>(?![=>])/.test(after)) [row.kind, row.why] = ["manual", "template arg"];
            else if ((addr & 0xfff) === 0) [row.kind, row.why] = ["unsure", "page-aligned (section bound, size or base?)"];
            else if (/^0*F+$/i.test(m[1]) || /^0*FF+0*$/i.test(m[1])) [row.kind, row.why] = ["unsure", "mask"];
            else if (KNOWN.has(addr)) [row.kind, row.why] = ["unsure", "known constant"];
            else if (NAMEY.test(before)) [row.kind, row.why] = ["unsure", `name: ${NAMEY.exec(before)![1]}`];
            rows.push(row);
        }
        i += m[0].length;
    }
    return rows;
}

// rewrite the wrap rows (right to left per line so columns stay valid)
export function applyText(text: string, rows: Row[]): string {
    const lines = text.split("\n");
    for (const r of [...rows].filter((r) => r.kind === "wrap").sort((a, b) => b.line - a.line || b.col - a.col)) {
        const l = lines[r.line - 1], c = r.col - 1;
        if (l.slice(c, c + r.lit.length) !== r.lit) throw new Error(`${r.file}:${r.line}:${r.col} moved`);
        lines[r.line - 1] = l.slice(0, c) + `TS3A(${r.lit})` + l.slice(c + r.lit.length);
    }
    return lines.join("\n");
}

export function addInclude(text: string): string {
    if (text.includes('#include "ts3addr.h"')) return text;
    const lines = text.split("\n");
    let last = -1;
    for (let k = 0; k < lines.length && k < 200; k++) if (/^#include\s*</.test(lines[k])) last = k;
    const eol = text.includes("\r\n") ? "\r" : "";
    lines.splice(last + 1, 0, INCLUDE + eol);
    return lines.join("\n");
}

export function sourceFiles(dir = SRC): string[] {
    return readdirSync(dir).filter((f) => /\.(cpp|h)$/.test(f) && !/test/.test(f) && f !== "ts3addr.h").sort();
}
export const generated = (text: string) => /generated (by|from)/i.test(text.split("\n").slice(0, 3).join("\n"));

// ---- gen: Steam -> other pairs for TS3A_TABLE ----
export function gen(csv: string, needed: number[], allowInferred: boolean, src = "map"): { header: string; errors: string[]; inferred: number } {
    const lines = csv.trim().split(/\r?\n/), head = csvRow(lines[0]);
    const ci = (k: string) => head.indexOf(k);
    const rank = (k: string) => (k === "exact" ? 3 : k === "masked" ? 2 : k === "near" || k === "ref" || k === "offset-changed" ? 1 : 0);
    const best = new Map<number, { nw: number; kind: string }>();
    for (const l of lines.slice(1)) {
        const c = csvRow(l), ref = parseInt(c[ci("ref")], 16), nw = parseInt(c[ci("new")], 16), kind = c[ci("kind")];
        if (isNaN(ref)) continue;
        if (isNaN(nw)) { if (!best.has(ref)) best.set(ref, { nw, kind }); continue; }
        const cur = best.get(ref);
        if (!cur || rank(kind) > rank(cur.kind)) best.set(ref, { nw, kind });
    }
    const errors: string[] = [];
    let inferred = 0;
    const pairs: [number, number][] = [];
    for (const a of [...new Set(needed)].sort((x, y) => x - y)) {
        const b = best.get(a);
        if (!b) { errors.push(`${hx(a)} not in the map`); continue; }
        if (rank(b.kind) < 2) { if (!allowInferred || rank(b.kind) === 0) { errors.push(`${hx(a)} kind ${b.kind}${rank(b.kind) ? " (needs --allow-inferred)" : ""}`); continue; } inferred++; }
        pairs.push([a, b.nw]);
    }
    const header = [
        `// Generated by tools/addr-codemod.ts gen from ${src}: derived from EA bytes, never commit. ${pairs.length} pairs, ${inferred} inferred.`,
        "#pragma once",
        "constexpr unsigned long ts3addr_pairs[][2] = {",
        ...(pairs.length ? pairs.map(([a, b]) => `    {${hx(a)}, ${hx(b)}},`) : ["    {0, 0},"]),
        "};",
        `constexpr int ts3addr_count = ${pairs.length};`,
        "",
    ].join("\n");
    return { header, errors, inferred };
}

const hx = (a: number) => "0x" + a.toString(16).toUpperCase().padStart(8, "0");

function selfCheck() {
    const ok = (c: boolean, what: string) => { if (!c) { console.error(`addr-codemod self-check FAILED: ${what}`); process.exit(1); } };
    const src = [
        "static const DWORD EA_MALLOC = 0x004E69D0, EA_FREE = 0x004E5920;",  // 1: static init -> wrap x2
        "x = Call(0x00D7E560); // 0x00D7E561",                                  // 2: wrap, comment skip
        'Log("call 0xAB12AF at %p", 0x00AB12AFu); /* 0x00AB12B0 */',            // 3: string + block comment skip, suffix kept
        "switch (a) { case 0x00939100: return 1; }",                            // 4: case label
        "__asm { jmp dword ptr [edx * 4 + 0x00E59880] }",                       // 5: asm
        "#if 0x00939100 > 0",                                                   // 6: #if
        "#define K_SITE 0x00939170",                                            // 7: #define -> wrap
        "DWORD kSize = 0x00800000, kMask = 0x00FFFFFF, h = 0x01000193, big = 0x80000000, small = 0x1000;",  // 8: unsure x3 + out of range
        "DWORD maxBytes = 0x00D7E570; g = *(DWORD*)0x011CB920; iat = 0x00F9517C;",  // 9: name -> unsure, data wrap x2
        "y = TS3A(0x00D7E560);",                                                // 10: already wrapped
        "T<0x00D7E560> t; v[0x00D7E560] = 1; ok = a < 0x00D7E560 || a >= 0x00D7E570;",  // 11: template, [], comparison wraps
        "{ 0x00D718CC, 6, {0x8D, 0x90} },",                                     // 12: aggregate -> wrap
    ].join("\n");
    const rows = scanText(src, "t.cpp");
    const at = (l: number) => rows.filter((r) => r.line === l).map((r) => r.kind + (r.why ? ":" + r.why.split(" ")[0] : "")).join(",");
    ok(at(1) === "wrap,wrap", "static initializer wrap " + at(1));
    ok(at(2) === "wrap", "line comment " + at(2));
    ok(at(3) === "wrap" && rows.find((r) => r.line === 3)!.lit === "0x00AB12AFu", "string/block comment " + at(3));
    ok(at(4) === "manual:case", "case " + at(4));
    ok(at(5) === "manual:inline", "asm " + at(5));
    ok(at(6) === "manual:#if", "#if " + at(6));
    ok(at(7) === "wrap", "#define " + at(7));
    ok(at(8) === "unsure:page-aligned,unsure:mask,unsure:known", "non-address " + at(8));
    ok(at(9) === "unsure:name:,wrap,wrap" && rows.filter((r) => r.line === 9).map((r) => r.sect).join() === ".text,.data,.rdata", "data ranges " + at(9));
    ok(at(10) === "wrapped", "idempotent scan " + at(10));
    ok(at(11) === "manual:template,manual:inside,wrap,wrap", "template/[] " + at(11));
    ok(at(12) === "wrap", "aggregate " + at(12));
    const once = applyText(src, rows), twice = applyText(once, scanText(once, "t.cpp"));
    ok(once === twice, "apply idempotent");
    ok(once.includes("EA_MALLOC = TS3A(0x004E69D0), EA_FREE = TS3A(0x004E5920);") && once.includes("TS3A(0x00AB12AFu)") && once.includes('"call 0xAB12AF') && once.includes("case 0x00939100:") && once.includes("// 0x00D7E561"), "apply text");
    ok(scanText(once, "t.cpp").every((r) => r.kind !== "wrap"), "nothing left to wrap");
    const inc = addInclude("// x\r\n#include <windows.h>\r\n#include <math.h>\r\nint a;\r\n");
    ok(inc.split("\r\n")[3].startsWith('#include "ts3addr.h"') && addInclude(inc) === inc, "include insert");
    ok(generated("// Generated by tools/x.py (do not edit)\n") && !generated("// ts3native\n"), "generated header");

    const csv = 'ref,new,kind,count,delta,window,funcOff,hint,label,where\n0x00D7E560,0x00D7F560,exact,1,4096,64,+0x0,,"a, b",x\n0x004E69D0,0x004E79D0,masked,1,,,,,,\n0x004E5920,0x004E6920,near,2,,,,,,\n0x011CB920,0x011CC920,ref,3,,,,,,\n0x00939100,,missing,0,,,,0x0093A100,,\n';
    const g1 = gen(csv, [0x4e69d0, 0xd7e560, 0x4e5920, 0x11cb920], false);
    ok(g1.errors.length === 2 && g1.errors[0].startsWith("0x004E5920 kind near"), "gen strict " + g1.errors.join("; "));
    const g2 = gen(csv, [0xd7e560, 0x4e69d0, 0x4e5920, 0x11cb920, 0xd7e560], true);
    ok(g2.errors.length === 0 && g2.inferred === 2 && /\{0x004E5920, 0x004E6920\},\n {4}\{0x004E69D0, 0x004E79D0\},\n {4}\{0x00D7E560, 0x00D7F560\},\n {4}\{0x011CB920, 0x011CC920\},/.test(g2.header) && g2.header.includes("ts3addr_count = 4;"), "gen sorted");
    const g3 = gen(csv, [0x939100, 0x123456], true);
    ok(g3.errors.length === 2 && g3.errors[0].includes("not in the map") && g3.errors[1].includes("kind missing"), "gen missing " + g3.errors.join("; "));
    console.log("addr-codemod self-check: ok");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
    const { values: v, positionals } = parseArgs({ allowPositionals: true, options: { apply: { type: "boolean" }, map: { type: "string" }, out: { type: "string" }, "allow-inferred": { type: "boolean" }, "self-check": { type: "boolean" } } });
    const cmd = positionals[0] ?? "scan";
    if (v["self-check"]) selfCheck();
    else if (cmd !== "scan" && cmd !== "gen") { console.error("usage: node tools/addr-codemod.ts [scan] [--apply] | gen --map <csv> [--allow-inferred] [--out file] | --self-check"); process.exit(2); }
    else {
        const data = dataRanges();
        const all: Row[] = [], gens: string[] = [];
        for (const f of sourceFiles()) {
            const text = readFileSync(join(SRC, f), "utf8");
            const rows = scanText(text, f, data);
            if (!rows.length) continue;
            if (generated(text)) { gens.push(`${f} (${rows.length})`); continue; }
            all.push(...rows);
            if (v.apply && cmd === "scan" && rows.some((r) => r.kind === "wrap")) writeFileSync(join(SRC, f), applyText(text, rows));
        }
        if (cmd === "gen") {
            if (!v.map) { console.error("gen needs --map out/exe-addr-map/<exe>.csv"); process.exit(2); }
            const needed = all.filter((r) => r.kind === "wrap" || r.kind === "wrapped").map((r) => r.addr);
            const g = gen(readFileSync(v.map, "utf8"), needed, !!v["allow-inferred"], basename(v.map));
            for (const e of g.errors.slice(0, 40)) console.log(e);
            if (g.errors.length) { console.log(`gen FAILED: ${g.errors.length} addresses without a usable row`); process.exit(1); }
            const out = v.out ?? join(SRC, "out", "ts3addr-table.h");
            mkdirSync(dirname(out), { recursive: true });
            writeFileSync(out, g.header);
            console.log(`${new Set(needed).size} addresses, ${g.inferred} inferred -> ${out}`);
        } else {
            if (v.apply) { const hub = join(SRC, HUB); writeFileSync(hub, addInclude(readFileSync(hub, "utf8"))); }
            const by = new Map<string, Record<string, number>>();
            for (const r of all) { const m = by.get(r.file) ?? {}; m[r.kind] = (m[r.kind] ?? 0) + 1; by.set(r.file, m); }
            const cols = ["wrap", "wrapped", "unsure", "manual"];
            console.log("file".padEnd(26) + cols.map((c) => c.padStart(8)).join(""));
            for (const [f, m] of by) console.log(f.padEnd(26) + cols.map((c) => String(m[c] ?? 0).padStart(8)).join(""));
            const tot = (k: string) => all.filter((r) => r.kind === k).length;
            console.log(`total: ${cols.map((c) => `${c} ${tot(c)}`).join(", ")}; distinct addresses ${new Set(all.map((r) => r.addr)).size}; sections ${[".text", ...data.map((d) => d[2])].map((s) => `${s} ${all.filter((r) => r.sect === s).length}`).join(" ")}`);
            const manual = new Map<string, number>();
            for (const r of all.filter((r) => r.kind === "manual")) manual.set(r.why, (manual.get(r.why) ?? 0) + 1);
            console.log(`manual by reason: ${[...manual].map(([k, n]) => `${k} ${n}`).join(", ") || "none"}`);
            if (gens.length) console.log(`generated headers skipped (fix the generator): ${gens.join(", ")}`);
            console.log("unsure:");
            for (const r of all.filter((r) => r.kind === "unsure")) console.log(`  ${r.file}:${r.line}:${r.col} ${r.lit} ${r.sect} ${r.why}`);
            const out = join(repo, "out", "addr-codemod", "scan.csv");
            mkdirSync(dirname(out), { recursive: true });
            writeFileSync(out, "file,line,col,literal,section,kind,why\n" + all.map((r) => [r.file, r.line, r.col, r.lit, r.sect, r.kind, `"${r.why}"`].join(",")).join("\n") + "\n");
            console.log(`${v.apply ? "applied" : "dry run"}; all rows -> ${out}`);
        }
    }
}

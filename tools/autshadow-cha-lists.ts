// docs/218 §5 item 2 (G-M6 hierarchy part): the class-hierarchy overrides each [AutShadow] closure owner can dispatch to,
// for the per-definition guard on a game module whose bytes are not on the content accept list. Emits
// mods/ts3fixes/src/AutShadowChaLists.cs:
//   Methods: every checkable game method of the 5-hop class-hierarchy closure (tools/autonomy-tier2.ts closure, the same
//            run tools/mod-method-diff.ts labels v0-cha) of each owner in AutShadowLists.Owners, minus AutShadowLists.Methods
//            (those are hashed on every load already). Roots: a definition's own Test/CalculateScore roots, an implementor's
//            HowMuchItWantsSimToCome / get_MetaAds. The shared base path is left out: through InteractionDefinition.Test it
//            reaches every definition in the game, and definition receivers are covered by the exact-type check.
//   Owners:  per Methods entry, bit o = AutShadowLists.Owners[o]'s hierarchy closure reaches it.
// tools/autshadow-il-hashes.ts hashes these keys with AutShadowLists.Methods. Method names only (no game code).
// Usage: node tools/autshadow-cha-lists.ts [--asm game-copy/assemblies] [--index game-copy/analysis/callgraph/index.json] [--check]
//   --check: compare with the committed file instead of writing it (exit 1 when they differ).
import { readFileSync, writeFileSync } from 'node:fs';
import { defRoots } from './managed-callgraph.ts';

const T = await import('./autonomy-tier2.ts');
const OUT = 'mods/ts3fixes/src/AutShadowChaLists.cs';
const LISTS = readFileSync('mods/ts3fixes/src/AutShadowLists.cs', 'utf8');
const strings = (a: string, b: string) => [...LISTS.slice(LISTS.indexOf(a), LISTS.indexOf(b)).matchAll(/"([^"]*)"/g)].map((m) => m[1]);
const closureKeys = new Set(strings('string[] Methods = {', 'int[] MethodOwners = {'));
const owners = strings('string[] Owners = {', 'string[] OwnerSlots = {');
if (owners.length === 0 || owners.length > 31) throw new Error(`AutShadowLists.Owners: ${owners.length} owners`);
const BCL = new Set(['mscorlib', 'System', 'System.Xml']);
const checkable = (i: number) => {
  const m = T.ix.methods[i], decl = m.k.slice(0, m.k.indexOf('::')), name = m.k.slice(m.k.indexOf('::') + 2, m.k.indexOf('('));
  return !BCL.has(T.ix.asms[m.a]?.name) && !decl.includes('`') && !name.includes('`') && name !== '.cctor' && !m.k.includes('!');
};
const sets = owners.map((o) => {
  const impl = T.IMPL.includes(o);
  const roots = impl ? [...T.starts(`${o}::HowMuchItWantsSimToCome`), ...T.starts(`${o}::get_MetaAds`)] : defRoots(T.ix as never, o);
  if (!roots.length) throw new Error(`no roots for owner ${o}`);
  return new Set(T.closure(roots, impl ? undefined : o, 5).ids);
});
const ids = [...new Set(sets.flatMap((s) => [...s]))].filter((i) => checkable(i) && !closureKeys.has(T.ix.methods[i].k))
  .sort((a, b) => (T.ix.methods[a].k < T.ix.methods[b].k ? -1 : T.ix.methods[a].k > T.ix.methods[b].k ? 1 : 0));
const keys = ids.map((i) => T.ix.methods[i].k);
const masks = ids.map((i) => sets.reduce((b, s, j) => (s.has(i) ? b | (1 << j) : b), 0));
const rows: string[] = [];
for (let j = 0; j < masks.length; j += 16) rows.push('            ' + masks.slice(j, j + 16).map((b) => `${b},`).join(' '));
const body = `// Generated by tools/autshadow-cha-lists.ts from the call-graph index (docs/218 §5, G-M6 hierarchy part). Do not edit by hand.
// ${owners.length} owners of AutShadowLists, class-hierarchy closure 5 hops, minus AutShadowLists.Methods. Method names only (no game code).
namespace Ts3Fixes
{
    public static class AutShadowChaLists
    {
        // IL-hashed only in a game module whose bytes are not on the content accept list (AutShadow.cs ClosureSweep)
        public static readonly string[] Methods = {
${keys.map((k) => `            ${JSON.stringify(k)},`).join('\n')}
        };
        // per Methods entry, bit o = AutShadowLists.Owners[o]'s hierarchy closure reaches it
        public static readonly int[] Owners = {
${rows.join('\n')}
        };
    }
}
`.replace(/\n/g, '\r\n');
console.error(`hierarchy methods ${keys.length} (per owner ${sets.map((s) => s.size).join('/')})`);
if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== body) { console.error(`${OUT} differs from the index: rerun without --check`); process.exit(1); }
  console.error(`${OUT} up to date`);
} else writeFileSync(OUT, body);

// docs/206 §7.3: EA internal calls whose native body can write managed memory through an argument (a byref/out parameter
// or an array), for [AutShadow] Satb. While a worker job runs, a sim-thread call of one of these with an argument that
// points into shared memory (Boehm heap or static data) makes the sim stop the worker first (the write's range is unknown).
// Input: the managed call-graph index's methods.csv (game-copy/analysis/callgraph, `node tools/managed-callgraph.ts`) and
// game-copy/analysis/internal-calls-map.csv (the EA IC names the guard thunks cover). Output: native/ts3native/satb-ics.h
// (IC name -> argument dwords to scan; 32 when a by-value struct of unknown size comes first). Names only, no game code.
// Usage: node tools/satb-ic-classes.ts [--out <file>] | --self-check
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import assert from 'node:assert/strict';

const ROOT = join(import.meta.dirname, '..');
// by-value sizes in argument dwords [verified for Vector3/LotLocation/ResourceKey in docs/122 §14.8; the rest from the
// SimIFace field lists]; enums are 4 bytes; references (string, object, delegates, Type, arrays) 1 dword
const STRUCT_DW: Record<string, number> = {
  'Sims3.SimIFace.Vector3': 3, 'Sims3.SimIFace.Vector2': 2, 'Sims3.SimIFace.Quaternion': 4, 'Sims3.SimIFace.ResourceKey': 4,
  'Sims3.SimIFace.LotLocation': 3, 'Sims3.SimIFace.ObjectGuid': 2, 'Sims3.SimIFace.Rect': 4, 'Sims3.SimIFace.Matrix44': 16,
  'System.Decimal': 4,
};
const PRIM_DW: Record<string, number> = { bool: 1, byte: 1, sbyte: 1, short: 1, ushort: 1, char: 1, int: 1, uint: 1, float: 1,
  long: 2, ulong: 2, double: 2, string: 1, object: 1, IntPtr: 1, UIntPtr: 1, 'System.IntPtr': 1 };
const REF_TYPES = /^(System\.(Type|Delegate|Array|Object|String|Exception)|.*(Delegate|Callback|Handler))$/;
const ENUM_LIKE = /^Sims3\.SimIFace\.(eRoomDefinition|FloorFeatureFlags|LotDetailPriority|ThumbnailSize|ThumbnailSizeMask|ThumbnailTechnique|SACS\.DriverRequestFlags|TelemetryModuleId|TelemetryGroupId|CustomContent\.ExportContentType)$|^ScriptCore\..*\+e[A-Z]|^Sims3Launcher\./;

export type IcRow = { name: string; dw: number; params: string[] };
// dwords to scan for one parameter list, or 32 when an unknown by-value struct comes first; null = no byref/array parameter
export function classify(params: string[]): number | null {
  let dw = 0, unknown = false, writes = false;
  for (const p of params) {
    if (p.endsWith('&') || p.endsWith('[]')) { writes = true; dw += 1; continue; }
    if (PRIM_DW[p] !== undefined) dw += PRIM_DW[p];
    else if (STRUCT_DW[p] !== undefined) dw += STRUCT_DW[p];
    else if (REF_TYPES.test(p) || ENUM_LIKE.test(p)) dw += 1;
    else unknown = true, dw += 1;
  }
  if (!writes) return null;
  return Math.min(32, unknown ? 32 : dw + 1);  // + 1: a hidden struct-return pointer may come first
}
export function parseSig(sig: string): string[] {
  const inner = sig.slice(sig.indexOf('(') + 1, sig.lastIndexOf(')'));
  return inner ? inner.split(',') : [];
}

export function build(methodsCsv: string, mapCsv: string): IcRow[] {
  const ea = new Set(mapCsv.split('\n').slice(1).map(l => l.split(',')[0]).filter(Boolean));
  const rows: IcRow[] = [];
  for (const l of methodsCsv.split('\n')) {
    const m = /^"([^"]+)",([^,]*),([^,]*),/.exec(l);
    if (!m || !m[3] || !ea.has(m[3])) continue;
    const params = parseSig(m[1]), dw = classify(params);
    if (dw !== null && !rows.some(r => r.name === m[3])) rows.push({ name: m[3], dw, params });
  }
  return rows.sort((a, b) => a.name < b.name ? -1 : 1);
}

function header(rows: IcRow[]): string {
  return `// Generated by tools/satb-ic-classes.ts (docs/206 §7.3): EA ICs with a byref/out or array parameter, and how many argument
// dwords the [AutShadow] Satb sim-side check scans (32 = an unknown by-value struct comes first). Do not edit by hand.
struct SatbIcRow { const char* name; u8 dw; };
static const SatbIcRow kSatbIcs[] = {
${rows.map(r => `    {"${r.name}", ${r.dw}},`).join('\n')}
};
static const int SATB_NICS = ${rows.length};
`;
}

function selfCheck() {
  assert.equal(classify(['Sims3.SimIFace.Vector3', 'Sims3.SimIFace.LotLocation&', 'Sims3.SimIFace.eRoomDefinition']), 6);
  assert.equal(classify(['ulong', 'uint']), null);
  assert.equal(classify(['Sims3.SimIFace.PathData', 'float&']), 32);
  assert.equal(classify(['byte[]', 'int']), 3);
  assert.deepEqual(parseSig('A::B(int,Sims3.SimIFace.Vector3&)'), ['int', 'Sims3.SimIFace.Vector3&']);
  const csv = '"ScriptCore.World::World_GetLotLocationImpl(Sims3.SimIFace.Vector3,Sims3.SimIFace.LotLocation&,Sims3.SimIFace.eRoomDefinition)",ScriptCore,ScriptCore.World::World_GetLotLocationImpl,0\n' +
    '"ScriptCore.World::World_GetSeaLevelImpl()",ScriptCore,ScriptCore.World::World_GetSeaLevelImpl,0\n';
  const rows = build(csv, 'name,address\nScriptCore.World::World_GetLotLocationImpl,0x1\nScriptCore.World::World_GetSeaLevelImpl,0x2\n');
  assert.deepEqual(rows.map(r => [r.name, r.dw]), [['ScriptCore.World::World_GetLotLocationImpl', 6]]);
  assert.match(header(rows), /\{"ScriptCore\.World::World_GetLotLocationImpl", 6\},/);
  console.log('self-check ok');
}

if (process.argv.includes('--self-check')) selfCheck();
else {
  const gc = join(process.env.TS3_REPO ?? ROOT, 'game-copy', 'analysis');  // a worktree: TS3_REPO=<main checkout>
  const oi = process.argv.indexOf('--out');
  const out = oi >= 0 ? process.argv[oi + 1] : join(ROOT, 'native', 'ts3native', 'satb-ics.h');
  const rows = build(readFileSync(join(gc, 'callgraph', 'methods.csv'), 'utf8'), readFileSync(join(gc, 'internal-calls-map.csv'), 'utf8'));
  writeFileSync(out, header(rows));
  console.log(`${rows.length} ICs with byref/array parameters (${rows.filter(r => r.dw === 32).length} with an unknown struct first) -> ${out}`);
}
